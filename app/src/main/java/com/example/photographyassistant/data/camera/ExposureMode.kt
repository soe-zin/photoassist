     * Auto-exposure mode
     */
    AUTO,
    
    /**
     * Flash exposure mode
     */
    FLASH,
    
    /**
     * Manual exposure mode
     */
    MANUAL,
    
    /**
     * Off exposure mode
     */
    OFF
}