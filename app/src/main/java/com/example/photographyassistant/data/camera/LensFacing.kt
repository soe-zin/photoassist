package com.example.photographyassistant.data.camera

/**
 * Camera lens facing direction.
 */
enum class LensFacing {
    /**
     * Front-facing camera (selfie camera)
     */
    FRONT,
    
    /**
     * Back-facing camera (main camera)
     */
    BACK,
    
    /**
     * External camera
     */
    EXTERNAL
}