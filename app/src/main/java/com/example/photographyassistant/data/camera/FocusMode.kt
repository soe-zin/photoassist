package com.example.photographyassistant.data.camera

/**
 * Camera focus modes.
 */
enum class FocusMode {
    /**
     * Auto-focus mode
     */
    AUTO,
    
    /**
     * Macro focus mode
     */
    MACRO,
    
    /**
     * Electronic depth-of-field mode
     */
    EDOF,
    
    /**
     * Fixed focus mode
     */
    FIXED,
    
    /**
     * Infinity focus mode
     */
    INFINITY,
    
    /**
     * Manual focus mode
     */
    MANUAL
}